// One-off: turn Natural Earth's Scotland map subunit into a compact SVG path for the Waste Map.
// Usage: node web/scripts/build-coastline.mjs <path/to/ne_10m_admin_0_map_subunits.geojson>
// The input is read as plain JSON data only. Output: web/src/assets/scotland.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Keep in sync with BOX, W, H and project() in web/src/screens/WasteMap.tsx.
const BOX = { minLon: -8.2, maxLon: -0.6, minLat: 54.6, maxLat: 60.9 };
const W = 520, H = 640;
const project = (lat, lon) => ({
  x: ((lon - BOX.minLon) / (BOX.maxLon - BOX.minLon)) * W,
  y: (1 - (lat - BOX.minLat) / (BOX.maxLat - BOX.minLat)) * H,
});

const TOLERANCE = 0.45; // px, Douglas-Peucker
const MIN_AREA = 2;     // px², drop islets smaller than this

const input = process.argv[2];
if (!input) throw new Error("Pass the Natural Earth GeoJSON path as the first argument");
const geo = JSON.parse(readFileSync(input, "utf8"));
const feature = geo.features.find((f) => f?.properties?.SU_A3 === "SCT");
if (!feature) throw new Error("Scotland (SU_A3=SCT) not found");
const { type, coordinates } = feature.geometry;
const polygons = type === "Polygon" ? [coordinates] : type === "MultiPolygon" ? coordinates : [];

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const A = pts[a], B = pts[b];
    const dx = B.x - A.x, dy = B.y - A.y, len = Math.hypot(dx, dy);
    let best = -1, bestD = 0;
    for (let i = a + 1; i < b; i++) {
      // Closed rings start and end on the same point: fall back to distance from it.
      const d = len ? Math.abs(dy * (pts[i].x - A.x) - dx * (pts[i].y - A.y)) / len : Math.hypot(pts[i].x - A.x, pts[i].y - A.y);
      if (d > bestD) { bestD = d; best = i; }
    }
    if (bestD > tol) { keep[best] = 1; stack.push([a, best], [best, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const area = (pts) => Math.abs(pts.reduce((s, p, i) => { const q = pts[(i + 1) % pts.length]; return s + p.x * q.y - q.x * p.y; }, 0)) / 2;
const r = (v) => Math.round(v * 10) / 10;

let d = "", rings = 0;
for (const poly of polygons) {
  for (const ring of poly) {
    const pts = simplify(ring.filter((c) => Array.isArray(c) && Number.isFinite(c[0]) && Number.isFinite(c[1])).map(([lon, lat]) => project(lat, lon)), TOLERANCE);
    if (pts.length < 4 || area(pts) < MIN_AREA) continue;
    d += "M" + pts.slice(0, -1).map((p) => `${r(p.x)} ${r(p.y)}`).join("L") + "Z";
    rings++;
  }
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "assets", "scotland.ts");
writeFileSync(out,
  "// Generated by web/scripts/build-coastline.mjs from Natural Earth 1:10m Admin 0 map subunits (Scotland).\n" +
  "// Natural Earth data is in the public domain: https://www.naturalearthdata.com/about/terms-of-use/\n" +
  `// Projected to the Waste Map viewBox (${W}x${H}); ${rings} rings.\n` +
  `export const SCOTLAND_PATH =\n  ${JSON.stringify(d)};\n`);
console.log(`wrote ${out}: ${rings} rings, ${d.length} chars`);
